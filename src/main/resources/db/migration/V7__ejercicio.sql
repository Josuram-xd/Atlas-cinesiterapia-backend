-- Ficha de ejercicio. Borrado blando con deleted_at; version para control de concurrencia y ETag.
CREATE TABLE ejercicio (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                          VARCHAR(200)  NOT NULL,
    nombre_busqueda                 VARCHAR(200)  NOT NULL,
    region_id                       BIGINT        NOT NULL,
    categoria_id                    BIGINT        NOT NULL,
    estado                          VARCHAR(12)   NOT NULL DEFAULT 'BORRADOR',
    objetivo_terapeutico            VARCHAR(5000),
    estructuras_intervenidas        VARCHAR(5000),
    indicaciones                    VARCHAR(5000),
    precauciones_contraindicaciones VARCHAR(5000),
    posicion_paciente               VARCHAR(5000),
    posicion_fisioterapeuta         VARCHAR(5000),
    ejecucion                       VARCHAR(5000),
    comandos_verbales               VARCHAR(5000),
    dosis_series                    VARCHAR(100),
    dosis_repeticiones              VARCHAR(100),
    dosis_intensidad                VARCHAR(100),
    dosis_tiempo                    VARCHAR(100),
    dosis_descanso                  VARCHAR(100),
    dosis_frecuencia                VARCHAR(100),
    progresion                      VARCHAR(5000),
    errores_comunes                 VARCHAR(5000),
    cohorte                         VARCHAR(10),
    profesora_revisora              VARCHAR(150),
    creado_por                      BIGINT        NOT NULL,
    actualizado_por                 BIGINT,
    created_at                      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    publicado_at                    TIMESTAMP WITH TIME ZONE,
    archivado_at                    TIMESTAMP WITH TIME ZONE,
    deleted_at                      TIMESTAMP WITH TIME ZONE,
    version                         BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_ejercicio_region    FOREIGN KEY (region_id)       REFERENCES region_anatomica (id),
    CONSTRAINT fk_ejercicio_categoria FOREIGN KEY (categoria_id)    REFERENCES categoria_terapeutica (id),
    CONSTRAINT fk_ejercicio_creador   FOREIGN KEY (creado_por)      REFERENCES usuario (id),
    CONSTRAINT fk_ejercicio_editor    FOREIGN KEY (actualizado_por) REFERENCES usuario (id),
    CONSTRAINT ck_ejercicio_estado    CHECK (estado IN ('BORRADOR', 'PUBLICADO', 'ARCHIVADO'))
);

CREATE INDEX ix_ejercicio_atlas ON ejercicio (region_id, categoria_id, estado);
CREATE INDEX ix_ejercicio_estado ON ejercicio (estado, updated_at);

CREATE TABLE ejercicio_estudiante (
    ejercicio_id BIGINT       NOT NULL,
    posicion     INT          NOT NULL,
    nombre       VARCHAR(150) NOT NULL,
    PRIMARY KEY (ejercicio_id, posicion),
    CONSTRAINT fk_ejercicio_estudiante FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id) ON DELETE CASCADE
);

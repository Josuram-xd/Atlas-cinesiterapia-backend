-- Archivos de una ficha (video e imagenes). El binario vive en el almacenamiento externo (R2).
CREATE TABLE media (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejercicio_id   BIGINT       NOT NULL,
    tipo           VARCHAR(10)  NOT NULL,
    rol            VARCHAR(20),
    clave          VARCHAR(300) NOT NULL,
    nombre_archivo VARCHAR(200),
    content_type   VARCHAR(100) NOT NULL,
    tamano_bytes   BIGINT       NOT NULL,
    estado         VARCHAR(12)  NOT NULL DEFAULT 'PENDIENTE',
    orden          INT          NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_media_clave UNIQUE (clave),
    CONSTRAINT fk_media_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT ck_media_tipo CHECK (tipo IN ('VIDEO', 'IMAGEN')),
    CONSTRAINT ck_media_rol CHECK (rol IS NULL OR rol IN ('POSICION_INICIAL', 'POSICION_FINAL', 'TOMA_TERAPEUTA', 'OTRO')),
    CONSTRAINT ck_media_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADO'))
);

CREATE INDEX ix_media_ejercicio ON media (ejercicio_id, estado, orden);

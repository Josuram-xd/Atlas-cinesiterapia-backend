-- Metricas de uso. visita: una fila por apertura de ficha o del atlas (RF_032). sesion_uso: una fila por sesion de
-- uso; una sesion nueva empieza tras 30 min sin ping. fecha (UTC) y duracion_segundos estan desnormalizadas para
-- agregar con SQL estandar, portable entre PostgreSQL y H2.
CREATE TABLE visita (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT      NOT NULL,
    tipo         VARCHAR(10) NOT NULL,
    ejercicio_id BIGINT,
    fecha        DATE        NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_visita_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_visita_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT ck_visita_tipo CHECK (tipo IN ('ATLAS', 'FICHA')),
    CONSTRAINT ck_visita_ficha CHECK ((tipo = 'FICHA' AND ejercicio_id IS NOT NULL) OR (tipo = 'ATLAS' AND ejercicio_id IS NULL))
);

-- Visitas por periodo, ranking por ficha y usuarios activos.
CREATE INDEX ix_visita_fecha ON visita (fecha);
CREATE INDEX ix_visita_ejercicio_fecha ON visita (ejercicio_id, fecha);
CREATE INDEX ix_visita_usuario_fecha ON visita (usuario_id, fecha);
-- Anti-duplicados: ultima visita de un usuario al mismo destino.
CREATE INDEX ix_visita_usuario_creada ON visita (usuario_id, created_at);

CREATE TABLE sesion_uso (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT NOT NULL,
    inicio_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_ping_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    duracion_segundos BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_sesion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_sesion_duracion CHECK (duracion_segundos >= 0)
);

-- Sesion vigente de un usuario, promedio por periodo y usuarios activos.
CREATE INDEX ix_sesion_usuario_ping ON sesion_uso (usuario_id, ultimo_ping_at);
CREATE INDEX ix_sesion_inicio ON sesion_uso (inicio_at);
CREATE INDEX ix_sesion_ping ON sesion_uso (ultimo_ping_at);

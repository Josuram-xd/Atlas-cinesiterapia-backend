-- Catalogos: regiones anatomicas (con svg_id prefijado por vista) y categorias terapeuticas.
CREATE TABLE region_anatomica (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    vista  VARCHAR(10) NOT NULL,
    svg_id VARCHAR(60) NOT NULL,
    orden  INT         NOT NULL,
    CONSTRAINT uq_region_svg_id UNIQUE (svg_id),
    CONSTRAINT ck_region_vista CHECK (vista IN ('ANTERIOR', 'POSTERIOR'))
);

CREATE TABLE categoria_terapeutica (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    orden  INT          NOT NULL,
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);


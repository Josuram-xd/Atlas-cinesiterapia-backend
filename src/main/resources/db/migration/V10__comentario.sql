-- Comentarios de las fichas (hilos de un nivel) y reportes de usuarios. Borrado blando: estado ELIMINADO + deleted_at.
CREATE TABLE comentario (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejercicio_id BIGINT        NOT NULL,
    autor_id     BIGINT        NOT NULL,
    padre_id     BIGINT,
    texto        VARCHAR(1000) NOT NULL,
    estado       VARCHAR(12)   NOT NULL DEFAULT 'PUBLICADO',
    editado_at   TIMESTAMP WITH TIME ZONE,
    deleted_at   TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comentario_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT fk_comentario_autor FOREIGN KEY (autor_id) REFERENCES usuario (id),
    CONSTRAINT fk_comentario_padre FOREIGN KEY (padre_id) REFERENCES comentario (id),
    CONSTRAINT ck_comentario_estado CHECK (estado IN ('PUBLICADO', 'EN_REVISION', 'ELIMINADO'))
);

-- Listado de una ficha: raices recientes primero (padre_id NULL) y respuestas por padre.
CREATE INDEX ix_comentario_ficha ON comentario (ejercicio_id, padre_id, created_at);
CREATE INDEX ix_comentario_padre ON comentario (padre_id, created_at);
-- Cola de revision del admin (estado EN_REVISION).
CREATE INDEX ix_comentario_estado ON comentario (estado, created_at);
CREATE INDEX ix_comentario_autor ON comentario (autor_id);

-- Un reporte por (usuario, comentario).
CREATE TABLE reporte_comentario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comentario_id BIGINT NOT NULL,
    usuario_id    BIGINT NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reporte_comentario FOREIGN KEY (comentario_id) REFERENCES comentario (id),
    CONSTRAINT fk_reporte_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT uq_reporte_comentario_usuario UNIQUE (comentario_id, usuario_id)
);

CREATE INDEX ix_reporte_usuario ON reporte_comentario (usuario_id);

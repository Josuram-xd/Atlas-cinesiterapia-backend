CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo        VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    rol_perfil    VARCHAR(20)  NOT NULL,
    rol_sistema   VARCHAR(10)  NOT NULL DEFAULT 'USER',
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol_perfil CHECK (rol_perfil IN ('ESTUDIANTE', 'PROFESIONAL', 'PRACTICANTE', 'VISITANTE')),
    CONSTRAINT ck_usuario_rol_sistema CHECK (rol_sistema IN ('USER', 'ADMIN'))
);

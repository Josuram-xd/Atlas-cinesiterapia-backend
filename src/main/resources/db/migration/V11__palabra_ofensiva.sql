-- Lista de palabras ofensivas (filtro automatico de comentarios). palabra_normalizada: minusculas, sin tildes,
-- con sustituciones tipo 4->a / 3->e ya aplicadas y solo letras y espacios; es lo que compara el filtro.
CREATE TABLE palabra_ofensiva (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    palabra            VARCHAR(60) NOT NULL,
    palabra_normalizada VARCHAR(60) NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_palabra_ofensiva_normalizada UNIQUE (palabra_normalizada)
);

